const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('pet', {
  hover: (hovering) => ipcRenderer.send('hover-state', hovering),
  dragStart: () => ipcRenderer.send('drag-start'),
  dragMove: () => ipcRenderer.send('drag-move'),
  dragEnd: () => ipcRenderer.send('drag-end'),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  saveSettings: (patch) => ipcRenderer.send('save-settings', patch),
  quit: () => ipcRenderer.send('quit'),
  chooseModel: () => ipcRenderer.invoke('choose-model'),
  contextMenu: () => ipcRenderer.send('context-menu'),
  openChat: () => ipcRenderer.send('open-chat'),
  closeChat: () => ipcRenderer.send('close-chat'),
  chat: (messages) => ipcRenderer.invoke('chat', messages),
  captureScreen: () => ipcRenderer.invoke('capture-screen'),
  snipScreen: () => ipcRenderer.invoke('snip-screen'),
  snipDone: (dataUrl) => ipcRenderer.send('snip-done', dataUrl),
  onSnipImage: (cb) => ipcRenderer.on('snip-image', (_e, d) => cb(d)),
  listMusic: () => ipcRenderer.invoke('list-music'),
  tts: (text) => ipcRenderer.invoke('tts', text),
  noMusic: () => ipcRenderer.send('no-music'),
  onToggleMusic: (cb) => ipcRenderer.on('toggle-music', () => cb()),
  voiceDuck: (on) => ipcRenderer.send('voice-duck', !!on),
  onVoiceDuck: (cb) => ipcRenderer.on('voice-duck', (_e, on) => cb(on)),
  onNextTrack: (cb) => ipcRenderer.on('next-track', () => cb()),
  onSummon: (cb) => ipcRenderer.on('summon', () => cb()),
  // 窗口被收起时让 3D 渲染整体休眠，别在后台空转
  onPause: (cb) => ipcRenderer.on('pet-pause', () => cb()),
  onResume: (cb) => ipcRenderer.on('pet-resume', () => cb()),
  touch: () => ipcRenderer.send('user-touch'),
  onApplySettings: (cb) => ipcRenderer.on('apply-settings', (_e, s) => cb(s)),
  onSwitchModel: (cb) => ipcRenderer.on('switch-model', (_e, k) => cb(k)),
  onSetAct: (cb) => ipcRenderer.on('set-act', (_e, name) => cb(name)),
  onNextAct: (cb) => ipcRenderer.on('next-act', () => cb()),
  onToggleFairy: (cb) => ipcRenderer.on('toggle-fairy', () => cb()),
  onPetSay: (cb) => ipcRenderer.on('pet-say', (_e, d) => cb(d)),
  onPetCelebrate: (cb) => ipcRenderer.on('pet-celebrate', (_e, n) => cb(n)),
  onPetLook: (cb) => ipcRenderer.on('pet-look', () => cb()),
  onPetClip: (cb) => ipcRenderer.on('pet-clip', () => cb()),
  readClipboard: () => ipcRenderer.invoke('read-clipboard'),
  notify: (title, body) => ipcRenderer.send('pet-notify', { title, body }),
  // 离线语音输入（按住说话）
  asrStart: () => ipcRenderer.invoke('asr-start'),
  asrChunk: (buf) => ipcRenderer.send('asr-chunk', buf),
  asrEnd: () => ipcRenderer.invoke('asr-end'),
  asrCancel: () => ipcRenderer.send('asr-cancel'),
  onAsrPartial: (cb) => ipcRenderer.on('asr-partial', (_e, d) => cb(d)),
  onAsrError: (cb) => ipcRenderer.on('asr-error', (_e, d) => cb(d)),
  onAsrCommandDone: (cb) => ipcRenderer.on('asr-command-done', (_e, d) => cb(d)),
  voiceCommand: (action, raw) => ipcRenderer.send('voice-command', action, raw)
});
